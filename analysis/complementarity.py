"""Complementarity analysis: unique solves, pairwise overlap, greedy union curve, per-domain winners."""
import json, sys
sys.path.insert(0, "analysis")
from router import load_run, ROOT
cfg = json.load(open("analysis/systems.json"))
have = lambda p: (ROOT / p).exists() or (ROOT / p).with_suffix(".jsonl").exists()
D = {"calib": {}, "test": {}}
for n, sc in cfg["systems"].items():
    for sp in D:
        if sc.get(sp) and have(sc[sp]): D[sp][n] = load_run(sc[sp], sc["price"])
POOL = ["ds_harness_v2", "ds_base", "ds_harness", "qwen_ft", "nemo_ft"]
out = {}
for sp, R in D.items():
    S = [s for s in POOL + ["kimi_k3"] if s in R]
    T = sorted(set.intersection(*[set(R[s]) for s in S]))
    P = {s: {t for t in T if R[s][t]["pass"]} for s in S}
    print(f"\n===== {sp}: {len(T)} tasks, systems {S}")
    for s in S:
        others = set().union(*[P[o] for o in S if o != s])
        others_open = set().union(*[P[o] for o in S if o not in (s, "kimi_k3")])
        print(f"  {s:14s} solves {len(P[s]):2d}  unique(vs all) {len(P[s]-others):2d}  unique(vs other open) {len(P[s]-others_open):2d}")
    print("  pairwise: row solves & col fails")
    print("  " + " " * 14 + "".join(f"{c[:9]:>10s}" for c in S))
    for a in S: print(f"  {a:14s}" + "".join(f"{len(P[a]-P[b]):10d}" for b in S))
    # greedy union curve over open pool
    chosen, cur = [], set(); curve = []
    rem = [s for s in POOL if s in S]
    while rem:
        b = max(rem, key=lambda s: len(cur | P[s])); rem.remove(b); chosen.append(b); cur |= P[b]
        curve.append((b, len(cur)))
    print("  greedy union (open models):", " -> ".join(f"+{b}: {n}/{len(T)} ({n/len(T):.0%})" for b, n in curve))
    print(f"  union open + kimi: {len(cur | P.get('kimi_k3', set()))}/{len(T)}")
    ft_only = (P["qwen_ft"] | P["nemo_ft"]) - set().union(*[P[s] for s in ["ds_harness_v2", "ds_base", "ds_harness"]])
    print(f"  tasks ONLY a fine-tune solved (no DeepSeek variant): {len(ft_only)} {sorted(ft_only)}")
    if "kimi_k3" in P: print(f"  tasks ONLY a fine-tune solved that Kimi also failed: {sorted(ft_only - P['kimi_k3'])}")
    doms = sorted({t.split('.')[0] for t in T})
    print("  per-domain pass (n):")
    for d in doms:
        td = [t for t in T if t.startswith(d)]
        print(f"    {d:12s} n={len(td):2d} " + " ".join(f"{s[:8]}={sum(t in P[s] for t in td)}" for s in S))
    out[sp] = {"n": len(T), "solves": {s: len(P[s]) for s in S}, "curve": curve, "ft_only": sorted(ft_only),
               "pair": {a: {b: len(P[a]-P[b]) for b in S} for a in S}}
json.dump(out, open("runs/complementarity.json", "w"), indent=1)

# ---- export for slides/story.html ----
LABEL = {"ds_harness_v2": "DeepSeek + harness v2", "ds_base": "DeepSeek (no harness)", "ds_harness": "DeepSeek + harness v1",
         "qwen_ft": "Qwen 3.6 + Holo4 LoRA", "nemo_ft": "Nemotron 3.5 + Holo4 LoRA", "kimi_k3": "Kimi K3 (frontier)"}
exp = {"labels": LABEL}
for sp, R in D.items():
    S = [s for s in POOL + ["kimi_k3"] if s in R]
    T = sorted(set.intersection(*[set(R[s]) for s in S]))
    T.sort(key=lambda t: (-sum(R[s][t]["pass"] for s in S), t.split(".")[0], t))
    exp[sp] = {"systems": S, "tasks": T, "m": [[1 if R[s][t]["pass"] else 0 for t in T] for s in S],
               "curve": out[sp]["curve"], "n": len(T), "solves": out[sp]["solves"], "ft_only": out[sp]["ft_only"],
               "union_all": sum(any(R[s][t]["pass"] for s in S) for t in T)}
open("slides/complement_data.js", "w").write("// generated by analysis/complementarity.py\nwindow.COMPLEMENT = " + json.dumps(exp) + ";\n")
print("wrote slides/complement_data.js")
